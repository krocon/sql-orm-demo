package dev.krocon.shop.ep037;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import dev.krocon.shop.ShopJpaTest;
import jakarta.persistence.EntityManager;
import java.util.List;
import java.util.Map;
import javax.sql.DataSource;
import org.hibernate.boot.MetadataSources;
import org.hibernate.boot.registry.StandardServiceRegistry;
import org.hibernate.boot.registry.StandardServiceRegistryBuilder;
import org.hibernate.cfg.AvailableSettings;
import org.hibernate.tool.schema.spi.SchemaManagementException;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;

/**
 * Szenario aus dem Video: Feld name → fullName.
 * Für update/validate wird ein zweites, eigenes Hibernate gegen ein Hilfsschema mit dem ALTEN Stand gestartet.
 */
@ShopJpaTest
class DdlAutoTest {
  @Autowired DataSource dataSource;
  @Autowired JdbcClient jdbc;
  @Autowired EntityManager em;

  /** Alter Stand (vor der Umbenennung) in einem eigenen Schema, mit Daten. */
  void createOldSchema(String schema) {
    jdbc.sql("DROP SCHEMA IF EXISTS " + schema + " CASCADE").update();
    jdbc.sql("CREATE SCHEMA " + schema).update();
    jdbc.sql("CREATE TABLE " + schema + ".ep037_customers (id bigint GENERATED BY DEFAULT AS IDENTITY"
        + " PRIMARY KEY, email text NOT NULL UNIQUE, name text NOT NULL)").update();
    jdbc.sql("INSERT INTO " + schema + ".ep037_customers (email, name) VALUES"
        + " ('ana@shop.de', 'Ana Beispiel'), ('ben@shop.de', 'Ben Muster')").update();
  }

  /** Startet Hibernate nur mit der Entity Customer (fullName) und dem gewünschten ddl-auto-Modus. */
  void startHibernate(String ddlAuto, String schema) {
    StandardServiceRegistry registry = new StandardServiceRegistryBuilder()
        .applySetting(AvailableSettings.JAKARTA_NON_JTA_DATASOURCE, dataSource)
        .applySetting(AvailableSettings.HBM2DDL_AUTO, ddlAuto)
        .applySetting(AvailableSettings.DEFAULT_SCHEMA, schema)
        .build();
    try {
      new MetadataSources(registry).addAnnotatedClass(Customer.class)
          .buildMetadata().buildSessionFactory().close();
    } finally {
      StandardServiceRegistryBuilder.destroy(registry);
    }
  }

  List<String> columns(String schema) {
    return jdbc.sql("SELECT column_name FROM information_schema.columns"
            + " WHERE table_schema = ? AND table_name = 'ep037_customers' ORDER BY ordinal_position")
        .param(schema).query(String.class).list();
  }

  @AfterEach
  @Transactional(propagation = Propagation.NOT_SUPPORTED)
  void dropSchemas() {
    jdbc.sql("DROP SCHEMA IF EXISTS ep037_update CASCADE").update();
    jdbc.sql("DROP SCHEMA IF EXISTS ep037_old CASCADE").update();
  }

  @Test
  @Transactional(propagation = Propagation.NOT_SUPPORTED)   // Hibernate nutzt eigene Verbindungen
  void update_addsNewColumn_oldColumnStays_noData() {
    createOldSchema("ep037_update");

    startHibernate("update", "ep037_update");

    List<String> cols = columns("ep037_update");
    System.out.println("Spalten nach ddl-auto=update: " + cols);
    assertThat(cols).contains("name", "full_name");          // alte Spalte bleibt, neue kommt dazu
    List<Map<String, Object>> rows = jdbc.sql(
        "SELECT name, full_name FROM ep037_update.ep037_customers ORDER BY id").query().listOfRows();
    System.out.println("Daten nach ddl-auto=update: " + rows);
    assertThat(rows).allSatisfy(r -> assertThat(r.get("full_name")).isNull());   // nichts übernommen
  }

  @Test
  @Transactional(propagation = Propagation.NOT_SUPPORTED)
  void validate_failsOnMissingColumn() {
    createOldSchema("ep037_old");

    assertThatThrownBy(() -> startHibernate("validate", "ep037_old"))
        .isInstanceOf(SchemaManagementException.class)
        .hasMessageContaining("missing column [full_name]")
        .satisfies(e -> System.out.println("validate: " + e.getMessage()));
  }

  @Test
  void migration_renamesWithData() {
    // App-Schema: V370 (name) + V371 (RENAME COLUMN) → validate war beim Start grün, Daten sind da
    Customer ana = em.createQuery("select c from Ep037Customer c where c.email = 'ana@shop.de'",
        Customer.class).getSingleResult();
    assertThat(ana.getFullName()).isEqualTo("Ana Beispiel");
    assertThat(columns("public")).containsExactly("id", "email", "full_name");
  }
}
