-- Folge 022: bidirektional mit mappedBy (FK in ep022_order_items.order_id)
CREATE TABLE ep022_orders (
  id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label text NOT NULL
);
CREATE TABLE ep022_order_items (
  id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint REFERENCES ep022_orders (id),   -- bewusst nullable: zeigt die mappedBy-Falle
  sku      text NOT NULL,
  quantity integer NOT NULL
);

-- Unidirektionales @OneToMany ohne mappedBy/@JoinColumn: Hibernate erwartet eine Join-Tabelle
CREATE TABLE ep022_uni_orders (
  id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label text NOT NULL
);
CREATE TABLE ep022_uni_items (
  id  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku text NOT NULL
);
CREATE TABLE ep022_uni_orders_items (
  ep022_uni_order_id bigint NOT NULL REFERENCES ep022_uni_orders (id),
  items_id           bigint NOT NULL UNIQUE REFERENCES ep022_uni_items (id)
);
