-- Folge 020: drei ID-Strategien im Vergleich
CREATE SEQUENCE ep020_sequence_orders_seq START WITH 1 INCREMENT BY 50;   -- = allocationSize

CREATE TABLE ep020_sequence_orders (
  id          bigint PRIMARY KEY,                            -- ID kommt von Hibernate (Sequenz)
  customer_id bigint NOT NULL REFERENCES customers (id),
  total       numeric(10,2) NOT NULL
);

CREATE TABLE ep020_identity_orders (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- ID kommt erst beim INSERT
  customer_id bigint NOT NULL REFERENCES customers (id),
  total       numeric(10,2) NOT NULL
);

CREATE TABLE ep020_uuid_orders (
  id          uuid PRIMARY KEY,                              -- GenerationType.UUID (JPA 3.1+)
  customer_id bigint NOT NULL REFERENCES customers (id),
  total       numeric(10,2) NOT NULL
);
