-- Folge 021: Constraints gehören per Migration in die DB, nicht nur in Annotationen
CREATE TABLE ep021_orders (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_number      varchar(20) NOT NULL UNIQUE,
  customer_id       bigint NOT NULL REFERENCES customers (id),
  total             numeric(12,2) NOT NULL,
  status            varchar(20) NOT NULL
                    CHECK (status IN ('NEW', 'PAID', 'SHIPPED', 'CANCELLED')),
  -- @Embedded Address: Spalten in derselben Tabelle
  ship_street       varchar(100),
  ship_city         varchar(100),
  ship_zip          varchar(10),
  ship_country      varchar(2)
);
CREATE INDEX ep021_orders_customer_id_idx ON ep021_orders (customer_id);

-- ORDINAL-Falle: Status wird nur als Position (Zahl) gespeichert
CREATE TABLE ep021_ordinal_orders (
  id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status smallint NOT NULL
);
