-- Folge 032: JDBC-Batching. SEQUENCE (batchfähig) vs. IDENTITY (kein Insert-Batching).
CREATE SEQUENCE ep032_batch_item_seq INCREMENT BY 50;   -- passt zu allocationSize = 50

CREATE TABLE ep032_batch_items (
  id   bigint PRIMARY KEY,                               -- ID vergibt Hibernate aus der Sequence
  name text NOT NULL
);

CREATE TABLE ep032_identity_items (
  id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- ID erst nach dem INSERT bekannt
  name text NOT NULL
);
