-- Folge 023: Mini-Modell für die Cascade-REMOVE-Falle auf ein geteiltes Produkt
CREATE TABLE ep023_products (
  id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL
);
CREATE TABLE ep023_order_items (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES ep023_products (id),
  quantity   integer NOT NULL
);

-- DB-Variante statt Cascade in Java: order_items.order_id hat schon in V1
-- "REFERENCES orders (id) ON DELETE CASCADE" → DELETE FROM orders löscht die Positionen mit.
