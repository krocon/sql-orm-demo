-- Folge 036: Auditing-Felder, @SoftDelete und Envers-Historie (eigene Tabellen, shop bleibt unverändert)
CREATE TABLE ep036_orders (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status     text NOT NULL DEFAULT 'NEW',
  total      numeric(10,2) NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL,   -- @CreatedDate
  updated_at timestamptz,            -- @LastModifiedDate
  created_by text,                   -- @CreatedBy (AuditorAware)
  updated_by text,                   -- @LastModifiedBy
  deleted    boolean NOT NULL DEFAULT false   -- @SoftDelete (Standardspalte "deleted")
);

-- Envers: Revisionstabelle (DefaultRevisionEntity → REVINFO, Sequenz mit Schrittweite 50)
CREATE SEQUENCE revinfo_seq START WITH 1 INCREMENT BY 50;
CREATE TABLE revinfo (
  rev      integer PRIMARY KEY,
  revtstmp bigint                    -- Zeitpunkt in Millisekunden
);

-- Envers: eine Zeile pro Version; revtype 0 = ADD, 1 = MOD, 2 = DEL
CREATE TABLE ep036_orders_aud (
  id         bigint NOT NULL,
  rev        integer NOT NULL REFERENCES revinfo (rev),
  revtype    smallint,
  status     text,
  total      numeric(10,2),
  created_at timestamptz,
  updated_at timestamptz,
  created_by text,
  updated_by text,
  PRIMARY KEY (id, rev)
);

CREATE TABLE ep036_customers (
  id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email   text NOT NULL,
  deleted boolean NOT NULL DEFAULT false
);
